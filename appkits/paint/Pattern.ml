type t = string

let black p x y = Char.code p.[y land 7] land (0x80 lsr (x land 7)) <> 0
let make rows = String.init 8 (fun i -> Char.chr rows.(i land 7))
let solid = make [| 0xFF; 0xFF; 0xFF; 0xFF; 0xFF; 0xFF; 0xFF; 0xFF |]
let white = make [| 0; 0; 0; 0; 0; 0; 0; 0 |]
let grey = make [| 0xAA; 0x55; 0xAA; 0x55; 0xAA; 0x55; 0xAA; 0x55 |]

let palette =
  [
    solid;
    white;
    grey;
    (* a quarter, and three quarters *)
    make [| 0x88; 0x22; 0x88; 0x22; 0x88; 0x22; 0x88; 0x22 |];
    make [| 0x77; 0xDD; 0x77; 0xDD; 0x77; 0xDD; 0x77; 0xDD |];
    (* an eighth: sparse dots *)
    make [| 0x80; 0x00; 0x08; 0x00; 0x80; 0x00; 0x08; 0x00 |];
    (* diagonals, both ways *)
    make [| 0x01; 0x02; 0x04; 0x08; 0x10; 0x20; 0x40; 0x80 |];
    make [| 0x80; 0x40; 0x20; 0x10; 0x08; 0x04; 0x02; 0x01 |];
    (* horizontal and vertical lines *)
    make [| 0xFF; 0x00; 0x00; 0x00; 0xFF; 0x00; 0x00; 0x00 |];
    make [| 0x88; 0x88; 0x88; 0x88; 0x88; 0x88; 0x88; 0x88 |];
    (* bricks *)
    make [| 0xFF; 0x80; 0x80; 0x80; 0xFF; 0x08; 0x08; 0x08 |];
    (* a weave *)
    make [| 0xF8; 0x74; 0x22; 0x47; 0x8F; 0x17; 0x22; 0x71 |];
  ]
